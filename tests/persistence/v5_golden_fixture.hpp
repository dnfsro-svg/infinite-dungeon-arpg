        bytes[index + 224U] = kV5FullState[index];

    bytes[0U] = 'A'; bytes[1U] = 'R'; bytes[2U] = 'P'; bytes[3U] = 'G';
    bytes[4U] = 'S'; bytes[5U] = 'V'; bytes[6U] = '6'; bytes[7U] = '\0';
